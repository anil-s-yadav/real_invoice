  static pw.Widget _buildPaymentDetails(
    DocumentModel doc,
    List<PaymentDetail> payments,
    BusinessProfile profile, {
    PdfColor? primaryColor,
  }) {
    PaymentDetail? bankDetail;
    if (doc.selectedBankDetailId != null &&
        doc.selectedBankDetailId != 'none') {
      try {
        bankDetail = payments.firstWhere(
          (p) => p.id == doc.selectedBankDetailId,
        );
      } catch (_) {}
    }
    if (bankDetail == null &&
        doc.selectedBankDetailId != 'none' &&
        profile.bankName != null &&
        profile.bankName!.trim().isNotEmpty &&
        profile.accountNumber != null &&
        profile.accountNumber!.trim().isNotEmpty) {
      bankDetail = PaymentDetail(
        id: 'legacy',
        type: 'Bank',
        title: profile.bankName!,
        details: profile.accountNumber!,
        extra: profile.ifscCode,
      );
    }
    if (bankDetail == null && doc.selectedBankDetailId != 'none') {
      final banks = payments.where((p) => p.type == 'Bank').toList();
      if (banks.isNotEmpty) bankDetail = banks.first;
    }

    PaymentDetail? upiDetail;
    if (doc.selectedUpiDetailId != null && doc.selectedUpiDetailId != 'none') {
      try {
        upiDetail = payments.firstWhere((p) => p.id == doc.selectedUpiDetailId);
      } catch (_) {}
    }
    if (upiDetail == null &&
        doc.selectedUpiDetailId != 'none' &&
        profile.upiId != null &&
        profile.upiId!.trim().isNotEmpty) {
      upiDetail = PaymentDetail(
        id: 'legacy_upi',
        type: 'UPI',
        title: 'UPI',
        details: profile.upiId!,
      );
    }
    if (upiDetail == null && doc.selectedUpiDetailId != 'none') {
      final upis = payments.where((p) => p.type == 'UPI').toList();
      if (upis.isNotEmpty) upiDetail = upis.first;
    }

    final hasBank = bankDetail != null;
    final hasUpi = upiDetail != null;

    if (!doc.includePaymentDetails || doc.docType == DocumentType.receipt) {
      return pw.SizedBox();
    }
    if (!hasBank && !hasUpi) return pw.SizedBox();

    return pw.Container(
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Column(
            children: [
              pw.Container(
                width: 60,
                height: 60,
                padding: const pw.EdgeInsets.all(4),
                decoration: pw.BoxDecoration(
                  color: PdfColors.white,
                  borderRadius: const pw.BorderRadius.all(
                    pw.Radius.circular(6),
                  ),
                  border: pw.Border.all(color: PdfColors.grey400, width: 1),
                ),
                child: hasUpi
                    ? pw.BarcodeWidget(
                        barcode: pw.Barcode.qrCode(),
                        data:
                            'upi://pay?pa=${upiDetail.details}&pn=${Uri.encodeComponent(profile.businessName)}&am=${doc.totalAmount}',
                      )
                    : pw.BarcodeWidget(
                        barcode: pw.Barcode.qrCode(),
                        data: 'https://invoz.com',
                      ),
              ),
              pw.SizedBox(height: 4),
              pw.Text(
                'Scan to Pay',
                style: pw.TextStyle(
                  fontSize: 8,
                  fontWeight: pw.FontWeight.bold,
                  color: PdfColors.grey700,
                ),
              ),
            ],
          ),
          pw.SizedBox(width: 16),
          pw.Expanded(
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(
                  'PAYMENT DETAILS',
                  style: pw.TextStyle(
                    fontSize: 10,
                    fontWeight: pw.FontWeight.bold,
                    letterSpacing: 0.6,
                    color: primaryColor ?? PdfColors.grey800,
                  ),
                ),
                pw.SizedBox(height: 6),
                if (hasUpi)
                  pw.Padding(
                    padding: const pw.EdgeInsets.only(bottom: 4),
                    child: pw.Text(
                      'UPI (${upiDetail.title}): ${upiDetail.details}',
                      style: pw.TextStyle(
                        fontSize: 10,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                  ),
                if (hasBank) ...[
                  pw.Text(
                    'Bank: ${bankDetail.title}',
                    style: pw.TextStyle(
                      fontSize: 10,
                      fontWeight: pw.FontWeight.bold,
                    ),
                  ),
                  pw.SizedBox(height: 1),
                  pw.Text(
                    'A/C: ${bankDetail.details}',
                    style: const pw.TextStyle(fontSize: 10),
                  ),
                  if (bankDetail.extra != null &&
                      bankDetail.extra!.trim().isNotEmpty)
                    pw.Text(
                      'IFSC: ${bankDetail.extra}',
                      style: const pw.TextStyle(
                        fontSize: 9,
                        color: PdfColors.grey700,
                      ),
                    ),
                ],
              ],
            ),
          ),
        ],
      ),
    );
  }

  static pw.Widget _buildTable(
    DocumentModel doc, {
    required bool isPremium,
    PdfColor? primaryColor,
  }) {
    final headers = ['Item', 'Qty', 'Price', 'Tax', 'Total'];
    final data = doc.items.map((item) {
      return [
        item.title,
        item.quantity.toString(),
        CurrencyFormatter.format(item.unitPrice, symbol: 'Rs.'),
        item.taxPercent > 0 ? '${item.taxPercent}%' : '-',
        CurrencyFormatter.format(item.lineTotal, symbol: 'Rs.'),
      ];
    }).toList();

    if (isPremium) {
      return pw.TableHelper.fromTextArray(
        headers: headers,
        data: data,
        border: null,
        headerStyle: pw.TextStyle(
          color: PdfColors.white,
          fontWeight: pw.FontWeight.bold,
          fontSize: 10,
        ),
        headerDecoration: pw.BoxDecoration(
          color: primaryColor ?? PdfColors.blue,
        ),
        rowDecoration: const pw.BoxDecoration(
          border: pw.Border(
            bottom: pw.BorderSide(color: PdfColors.grey300, width: 0.5),
          ),
        ),
        cellStyle: const pw.TextStyle(fontSize: 10),
        cellAlignments: {
          0: pw.Alignment.centerLeft,
          1: pw.Alignment.center,
          2: pw.Alignment.centerRight,
          3: pw.Alignment.center,
          4: pw.Alignment.centerRight,
        },
      );
    } else {
      return pw.TableHelper.fromTextArray(
        headers: headers,
        data: data,
        border: const pw.TableBorder(
          bottom: pw.BorderSide(color: PdfColors.grey400),
          horizontalInside: pw.BorderSide(color: PdfColors.grey300),
        ),
        headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 10),
        cellStyle: const pw.TextStyle(fontSize: 10),
        cellAlignments: {
          0: pw.Alignment.centerLeft,
          1: pw.Alignment.center,
          2: pw.Alignment.centerRight,
          3: pw.Alignment.center,
          4: pw.Alignment.centerRight,
        },
      );
    }
  }

  static pw.Widget _buildSummaryRow(
    String label,
    String value, {
    bool isBold = false,
    double size = 10,
    PdfColor? color,
  }) {
    return pw.Padding(
      padding: const pw.EdgeInsets.symmetric(vertical: 2),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text(
            label,
            style: pw.TextStyle(
              fontSize: size,
              fontWeight: isBold ? pw.FontWeight.bold : pw.FontWeight.normal,
              color: color,
            ),
          ),
          pw.Text(
            value,
            style: pw.TextStyle(
              fontSize: size,
              fontWeight: isBold ? pw.FontWeight.bold : pw.FontWeight.normal,
              color: color,
            ),
          ),
        ],
      ),
    );
  }

