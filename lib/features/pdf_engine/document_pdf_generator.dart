  static final Map<String, Uint8List> _imageCache = {};

  static Future<Uint8List?> _fetchImageBytes(String path) async {
    if (path.isEmpty) return null;
    if (_imageCache.containsKey(path)) return _imageCache[path];

    try {
      // 1. Resolve local path via ImageCacheService if it's a remote URL
      // For caching key, we use a hash of the URL to ensure uniqueness
      String cacheKey = path.startsWith('http')
          ? 'pdf_img_${path.hashCode}'
          : '';
      String? resolvedPath = path.startsWith('http')
          ? await ImageCacheService.cacheImage(
              pathOrUrl: path,
              cacheKey: cacheKey,
            )
          : path;

      if (resolvedPath != null) {
        if (resolvedPath.startsWith('http')) {
          // Fallback to direct HTTP if caching failed but it's still a URL
          final response = await http
              .get(Uri.parse(resolvedPath))
              .timeout(const Duration(seconds: 5));
          if (response.statusCode == 200) {
            _imageCache[path] = response.bodyBytes;
            return response.bodyBytes;
          }
        } else {
          // Read local file
          final file = File(resolvedPath);
          if (await file.exists()) {
            final bytes = await file.readAsBytes();
            _imageCache[path] = bytes; // cache in-memory by original path
            return bytes;
          }
        }
      }
    } catch (_) {}
    return null;
  }

  static Future<Uint8List> generate({
    required DocumentModel document,
    required BusinessProfile profile,
    required List<PaymentDetail> payments,
    String? templateId,
  }) async {
    final pdf = pw.Document(
      title: '${document.docType.displayName} ${document.docNumber}',
      author: profile.businessName.isNotEmpty ? profile.businessName : 'invoz',
    );

    final selectedTemplate = templateId ?? document.templateId;
    final Uint8List? logoBytes = profile.logoPath != null
        ? await _fetchImageBytes(profile.logoPath!)
        : null;
    final Uint8List? signatureBytes = profile.signaturePath != null
        ? await _fetchImageBytes(profile.signaturePath!)
        : null;

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        footer: (context) => pw.Container(
          margin: const pw.EdgeInsets.only(top: 16),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text(
                'Generated by Invoz App',
                style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey),
              ),
              pw.Text(
                'Page ${context.pageNumber} of ${context.pagesCount}',
                style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey),
              ),
            ],
          ),
        ),
        build: (context) {
          if (selectedTemplate == TemplateRegistry.premiumModern) {
            return _buildPremiumModern(
              context,
              document,
              profile,
              payments: payments,
              logoBytes: logoBytes,
              signatureBytes: signatureBytes,
            );
          }
          if (selectedTemplate == TemplateRegistry.elegantCenter) {
            return _buildElegantCenter(
              context,
              document,
              profile,
              payments: payments,
              logoBytes: logoBytes,
              signatureBytes: signatureBytes,
            );
          }
          return _buildFreeClassic(
            context,
            document,
            profile,
            payments: payments,
            logoBytes: logoBytes,
            signatureBytes: signatureBytes,
          );
        },
      ),
    );

    return pdf.save();
  }

